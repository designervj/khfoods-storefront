export function translateStatic(text: string, locale: Locale = DEFAULT_LOCALE): string {
  if (locale !== "zh") return text;
  return zhTranslations[text] || text;
}

export function getLocalizedString(text: LocalizedString | string | undefined, locale: Locale = DEFAULT_LOCALE): string {
  if (!text) return "";
  if (typeof text === "string") return translateStatic(text, locale);
  const value = text[locale] || text.en || "";
  return locale === "zh" && !text[locale] ? translateStatic(value, locale) : value;
}
